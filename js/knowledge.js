export function renderArticleReaderHtml(topicId = "fundamentals", lang = "en") {
    const isAr = lang === "ar";
    const topic = getKnowledgeTopic(topicId);
    const title = isAr ? topic.title : topic.titleEn;
    const category = isAr ? topic.category : topic.categoryEn;
    const readTime = isAr ? topic.readTime : topic.readTimeEn;
    const article = ENGLISH_ARTICLES[topic.id];
    const intro = isAr ? topic.intro : article.intro;
    const content = isAr ? topic.contentHtml : article.body;

    // Previous and next topics
    const currentIndex = KNOWLEDGE_TOPICS.findIndex((t) => t.id === topic.id);
    const prevIndex = (currentIndex - 1 + KNOWLEDGE_TOPICS.length) % KNOWLEDGE_TOPICS.length;
    const nextIndex = (currentIndex + 1) % KNOWLEDGE_TOPICS.length;
    const prevTopic = KNOWLEDGE_TOPICS[prevIndex];
    const nextTopic = KNOWLEDGE_TOPICS[nextIndex];

    const prevLabel = isAr ? `« ${prevTopic.title}` : `« ${prevTopic.titleEn}`;
    const nextLabel = isAr ? `${nextTopic.title} »` : `${nextTopic.titleEn} »`;
    const backLabel = isAr ? "↑ العودة إلى شبكة المعرفة" : "↑ Back to Network";

    return `
        <div class="article-reader-header">
            <div class="article-meta-row">
                <span class="article-topic-badge">
                    <span aria-hidden="true">${topic.num}</span>
                    <span>${category}</span>
                </span>
                <span class="article-read-time">
                    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="10"></circle><polyline points="12 6 12 12 16 14"></polyline></svg>
                    <span>${readTime}</span>
                </span>
            </div>
            <h2 class="article-main-title">${title}</h2>
        </div>

        <div class="article-intro-lead">
            <p>${intro}</p>
        </div>

        <div class="article-body-content">
            ${content}
        </div>

        <div class="article-reader-footer">
            <button 
                type="button" 
                class="article-nav-btn" 
                data-action="knowledge:select-topic" 
                data-topic-id="${prevTopic.id}"
                aria-label="${isAr ? "المقال السابق: " + prevTopic.title : "Previous: " + prevTopic.titleEn}">
                ${prevLabel}
            </button>
            <button 
                type="button" 
                class="article-nav-btn btn-back-to-network" 
                data-action="knowledge:back-to-top"
                aria-label="${backLabel}">
                ${backLabel}
            </button>
            <button 
                type="button" 
                class="article-nav-btn" 
                data-action="knowledge:select-topic" 
                data-topic-id="${nextTopic.id}"
                aria-label="${isAr ? "المقال التالي: " + nextTopic.title : "Next: " + nextTopic.titleEn}">
                ${nextLabel}
            </button>
        </div>
    `;
}
